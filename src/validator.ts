export interface ValidationIssue {
  path: string;
  code: string;
  message: string;
}

export interface EntityProfileValidation {
  valid: boolean;
  errors: ValidationIssue[];
  warnings: string[];
  scope: "local-structural-check";
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isHttpUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return (url.protocol === "http:" || url.protocol === "https:") && !url.username && !url.password;
  } catch {
    return false;
  }
}

/**
 * Performs a local structural check of the subset generated by this project.
 * It is not a full Schema.org validator and does not verify the entity or its claims.
 */
export function validateEntityProfile(value: unknown): EntityProfileValidation {
  const errors: ValidationIssue[] = [];
  const warnings: string[] = [];

  if (!isRecord(value)) {
    return {
      valid: false,
      errors: [{ path: "$", code: "invalid_object", message: "JSON-LD must be a JSON object." }],
      warnings: [],
      scope: "local-structural-check",
    };
  }

  if (value["@context"] !== "https://schema.org") {
    errors.push({ path: "$['@context']", code: "unsupported_context", message: "Expected https://schema.org." });
  }
  if (value["@type"] !== "Organization") {
    errors.push({ path: "$['@type']", code: "unsupported_type", message: "Expected @type Organization." });
  }
  if (typeof value.name !== "string" || !value.name.trim()) {
    errors.push({ path: "$.name", code: "required_name", message: "A non-empty name is required." });
  }

  if (value.url !== undefined && (typeof value.url !== "string" || !isHttpUrl(value.url))) {
    errors.push({ path: "$.url", code: "invalid_url", message: "URL must be absolute HTTP(S) without embedded credentials." });
  }

  if (value["@id"] !== undefined && (typeof value["@id"] !== "string" || !isHttpUrl(value["@id"].replace(/#.*$/, "")))) {
    errors.push({ path: "$['@id']", code: "invalid_id", message: "@id must be based on an absolute HTTP(S) URL." });
  }

  if (value.alternateName !== undefined) {
    const aliases = Array.isArray(value.alternateName) ? value.alternateName : [value.alternateName];
    if (!aliases.length || aliases.some((item) => typeof item !== "string" || !item.trim())) {
      errors.push({ path: "$.alternateName", code: "invalid_alternate_name", message: "alternateName must be a non-empty string or an array of non-empty strings." });
    }
  }

  if (value.knowsLanguage !== undefined) {
    const languages = Array.isArray(value.knowsLanguage) ? value.knowsLanguage : [value.knowsLanguage];
    if (!languages.length || languages.some((item) => typeof item !== "string" || !item.trim())) {
      errors.push({ path: "$.knowsLanguage", code: "invalid_languages", message: "knowsLanguage must contain non-empty strings." });
    }
  }

  if (value.areaServed !== undefined) {
    const areas = Array.isArray(value.areaServed) ? value.areaServed : [value.areaServed];
    if (areas.some((area) => !isRecord(area) || typeof area.name !== "string" || !area.name.trim())) {
      errors.push({ path: "$.areaServed", code: "invalid_area_served", message: "Each areaServed item must be an object with a non-empty name." });
    }
  }

  if (value.sameAs !== undefined) {
    const links = Array.isArray(value.sameAs) ? value.sameAs : [value.sameAs];
    if (!links.length || links.some((link) => typeof link !== "string" || !isHttpUrl(link))) {
      errors.push({ path: "$.sameAs", code: "invalid_same_as", message: "sameAs must contain absolute HTTP(S) URLs without embedded credentials." });
    } else {
      warnings.push("sameAs URLs are structurally valid only; ownership and official status are not verified.");
    }
  }

  warnings.push("This is a local structural check of a limited Organization profile subset, not full Schema.org validation or independent entity verification.");

  return {
    valid: errors.length === 0,
    errors,
    warnings,
    scope: "local-structural-check",
  };
}
