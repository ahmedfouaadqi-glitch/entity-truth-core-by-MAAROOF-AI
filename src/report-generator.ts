type ReportCopy = (typeof COPY)[SupportedLang];

function present(value:unknown):boolean {
  if(typeof value==="string")return value.trim().length>0;
  if(Array.isArray(value))return value.length>0;
  if(value&&typeof value==="object")return Object.values(value).some(present);
  return value!==undefined&&value!==null&&value!==false;
}
function fields(input:EntityInput,result:EntityAuditResult,t:ReportCopy):FieldRow[] {
  const json=result.machinePack.jsonLd;
  return [
    {label:t.fields.name,supplied:present(input.name),included:present(json.name)},
    {label:t.fields.description,supplied:present(input.description)||present(input.headText),included:present(json.description)},
    {label:t.fields.url,supplied:present(input.url),included:present(json.url)},
    {label:t.fields.aliases,supplied:present(input.aliases),included:present(json.alternateName)},
    {label:t.fields.markets,supplied:present(input.markets),included:present(json.areaServed)},
    {label:t.fields.languages,supplied:present(input.knowsLanguages),included:present(json.knowsLanguage)},
    {label:t.fields.address,supplied:present(input.address),included:present(json.address)},
    {label:t.fields.contacts,supplied:present(input.contactPoints),included:present(json.contactPoint)},
    {label:t.fields.hours,supplied:present(input.openingHours),included:present(json.openingHoursSpecification)},
    {label:t.fields.services,supplied:present(input.services),included:present(json.hasOfferCatalog)},
    {label:t.fields.faqs,supplied:present(input.faqs),included:present(json.subjectOf)},
    {label:t.fields.serviceType,supplied:present(input.serviceType),included:present(json.serviceType)},
    {label:t.fields.facts,supplied:present(input.facts),included:present(input.facts)},
    {label:t.fields.profiles,supplied:present(input.officialProfiles),included:present(json.sameAs)}
  ];
}
function windowLabel(result:EntityAuditResult,t:ReportCopy):string {
  const window=result.factDensity.window;
  return window==="full"?t.fullText:t.firstWords.replace("{count}",String(window));
}
function markdownEscape(value:string):string {
  return value.replaceAll("\\","\\\\").replaceAll("|","\\|").replaceAll("<","&lt;").replaceAll("\r\n","<br>").replaceAll("\n","<br>");
}
function fenceFor(value:string):string {
  const tick=String.fromCharCode(96);
  let current=0,maxRun=0;
  for(const character of value){if(character===tick){current+=1;maxRun=Math.max(maxRun,current);}else current=0;}
  return tick.repeat(Math.max(3,maxRun+1));
}
function htmlEscape(value:string):string {
  return value.replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;").replaceAll('"',"&quot;").replaceAll("'","&#39;");
}
function htmlRows(rows:FieldRow[],t:ReportCopy):string {
  return rows.map(row=>"<tr><th scope=\"row\">"+htmlEscape(row.label)+"</th><td>"+(row.supplied?t.yes:t.notSupplied)+"</td><td>"+(row.included?t.yes:t.no)+"</td></tr>").join("");
}
function htmlSignals(result:EntityAuditResult,t:ReportCopy):string {
  if(!result.factDensity.candidateSignals.length)return "<p>"+htmlEscape(t.noPatterns)+"</p>";
  const labels={
    ar:{year:"سنة",percentage:"نسبة",standard:"معيار",scale:"حجم أو نطاق",currency:"عملة",email:"بريد إلكتروني",telephone:"هاتف",address:"عنوان",service:"خدمة"},
    ku:{year:"ساڵ",percentage:"ڕێژە",standard:"ستاندارد",scale:"قەبارە یان مەودا",currency:"دراو",email:"ئیمەیڵ",telephone:"تەلەفۆن",address:"ناونیشان",service:"خزمەتگوزاری"},
    en:{year:"Year",percentage:"Percentage",standard:"Standard",scale:"Scale",currency:"Currency",email:"Email",telephone:"Telephone",address:"Address",service:"Service"}
  }[result.language];
  return "<table><thead><tr><th>"+htmlEscape(t.category)+"</th><th>"+htmlEscape(t.originalValue)+"</th></tr></thead><tbody>"+
    result.factDensity.candidateSignals.map(signal=>"<tr><td>"+htmlEscape(labels[signal.category]??signal.category)+"</td><td dir=\"auto\">"+htmlEscape(signal.value)+"</td></tr>").join("")+
    "</tbody></table>";
}
function htmlList(items:string[],empty:string):string {
  if(!items.length)return "<p>"+htmlEscape(empty)+"</p>";
  return "<ul>"+items.map(item=>"<li>"+htmlEscape(item)+"</li>").join("")+"</ul>";
}

